"""Candidate CUDA builder for the archived August 2026 SVD LUT format.

The line kernel is the exact CUDA string from Photonix commit
``9f93c955779c11f7a8018e9200d63dddfa22ba23`` with comments removed.
The surrounding algorithm follows that commit's ``production/modal_lut.py``.
Archived factors were written before the commit, so generated bytes or scientific
parity must be checked before claiming this was their source. In particular, the
historical kernel reuses the first state's pressure-shifted line centers.

This module imports CuPy only when a build is requested. Use a CUDA 12 environment
with NumPy 2.1.3, SciPy 1.14.1 and CuPy 13.3.0 for a candidate historical run.
"""

from __future__ import annotations

from pathlib import Path
from time import perf_counter

import numpy as np

from .lut import GASES, MOLECULE_ID, sha256_file


VMR_REFERENCE = {
    "H2O": 1.0e-2,
    "CO2": 4.0e-4,
    "O3": 2.66e-8,
    "N2O": 3.2e-7,
    "CH4": 1.7e-6,
    "CO": 1.5e-7,
}
NT = 20
NP = 145
T_LOW = 170.0
T_HIGH = 330.0
P_LOW = 1.4e-5
P_HIGH = 1.189
STEP = 0.001
CUTOFF = 25.0
RANK = 64
_TEMPERATURE_NODES = np.array([200.0, 250.0, 296.0, 340.0])


def co2_continuum_sigma(
    nu: np.ndarray, temperature: np.ndarray, pressure: np.ndarray, cont
) -> np.ndarray:
    """Return the historical CO2 continuum below the chi/bandhead domain."""
    if nu.min() < 0 or nu.max() >= 2000:
        raise ValueError("Candidate builder supports only the 635..1265 cm^-1 thermal domain")
    sc = np.interp(nu, cont["co2_nu"], cont["co2_S"], left=0.0, right=0.0)
    exponent = nu[None, :] * (1.4387752 / temperature[:, None])
    radiation = np.where(
        exponent <= 0.01,
        0.5 * exponent * nu[None, :],
        np.where(
            exponent <= 10.0,
            nu[None, :] * (1 - np.exp(-exponent)) / (1 + np.exp(-exponent)),
            nu[None, :],
        ),
    )
    density = (pressure[:, None] * 1013.25 / 1013.0) * (296.0 / temperature[:, None])
    return sc[None, :] * density * 1e-20 * radiation


def build_block(
    pack_dir: Path, output: Path, gas: str, start: int, end: int, *, overwrite: bool = False
) -> dict:
    """Generate one 10 cm^-1 SVD factor block with the historical candidate kernel."""
    if gas not in GASES or end - start != 10 or start < 635 or end > 1265 or (start - 635) % 10:
        raise ValueError("A block must be one aligned 10 cm^-1 interval inside 635..1265")
    output = Path(output)
    if output.exists() and not overwrite:
        raise FileExistsError(output)
    try:
        import cupy as cp
    except ImportError as exc:
        raise RuntimeError("CuPy and a CUDA GPU are required for LUT construction") from exc

    pack_dir = Path(pack_dir)
    kernel_path = Path(__file__).with_name("historical_kernel.cu")
    kernel = cp.RawKernel(kernel_path.read_text(encoding="utf-8"), "dtau_kernel")
    started = perf_counter()
    with np.load(pack_dir / "lineas.npz", allow_pickle=False) as source:
        lines = {name: source[name] for name in source.files}
    with np.load(pack_dir / "qtab.npz", allow_pickle=False) as source:
        qtab = {name: source[name] for name in source.files}
    with np.load(pack_dir / "cont.npz", allow_pickle=False) as source:
        continuum = {name: source[name] for name in source.files}

    temperature_axis = np.linspace(T_LOW, T_HIGH, NT)
    pressure_axis = np.logspace(np.log10(P_LOW), np.log10(P_HIGH), NP)
    temperature, pressure = np.meshgrid(temperature_axis, pressure_axis, indexing="ij")
    temperature, pressure = temperature.ravel(), pressure.ravel()
    air_pressure = np.maximum(pressure * (1 - VMR_REFERENCE[gas]), 0.0)
    own_pressure = pressure * VMR_REFERENCE[gas]
    nu = np.arange(start, end + STEP / 2, STEP)
    sigma = np.zeros((temperature.size, nu.size), dtype=np.float64)
    q_interp = np.array([np.interp(temperature, qtab["TGRID"], row) for row in qtab["Q"]])
    molecule = lines["mol"][lines["iso_idx"]]
    chosen = (
        (lines["nu0"] >= start - CUTOFF)
        & (lines["nu0"] <= end + CUTOFF)
        & (molecule == MOLECULE_ID[gas])
    )
    if chosen.any():
        isotope = lines["iso_idx"][chosen]
        center = lines["nu0"][chosen]
        strength_ref = lines["Sref"][chosen]
        lower_energy = lines["Elow"][chosen]
        air_width = lines["g_air"][chosen]
        self_width = lines["g_self"][chosen]
        exponent = lines["n_air"][chosen]
        shift = lines["shift"][chosen]
        mixing = lines["Y"][chosen]
        mass = lines["Wg"][isotope]
        t_ref = float(qtab["TREF"])
        c2 = 1.4387752
        q_at_t = q_interp[isotope].T
        q_ref = qtab["Qref"][isotope][None, :]
        center_2d = center[None, :]
        temperature_2d = temperature[:, None]
        strength = (
            strength_ref[None, :]
            * q_ref
            / q_at_t
            * np.exp(-c2 * lower_energy[None, :] / temperature_2d)
            / np.exp(-c2 * lower_energy[None, :] / t_ref)
            * (1 - np.exp(-c2 * center_2d / temperature_2d))
            / (1 - np.exp(-c2 * center_2d / t_ref))
        )
        gamma = (t_ref / temperature_2d) ** exponent[None, :] * (
            air_width[None, :] * air_pressure[:, None] + self_width[None, :] * own_pressure[:, None]
        )
        doppler = center_2d * 3.5810e-7 * np.sqrt(temperature_2d / mass[None, :])
        voigt_width = 0.5346 * gamma + np.sqrt(0.2166 * gamma**2 + doppler**2)
        shifted = center_2d + shift[None, :] * air_pressure[:, None]
        if gas == "CO2" and mixing.any():
            y_values = np.ascontiguousarray(
                np.array([np.interp(temperature, _TEMPERATURE_NODES, row) for row in mixing]).T
            )
        else:
            y_values = np.zeros_like(strength)

        def device(array: np.ndarray, dtype=np.float64):
            return cp.asarray(np.ascontiguousarray(array, dtype=dtype))

        result = cp.zeros(sigma.shape, dtype=cp.float64)
        kernel(
            (int((result.size + 255) // 256),),
            (256,),
            (
                device(nu),
                np.int32(nu.size),
                device(shifted[0]),
                np.int32(center.size),
                device(strength),
                device(gamma),
                device(doppler),
                device(voigt_width),
                device(y_values),
                device(np.full(center.size, gas == "CO2"), np.int32),
                device(pressure),
                np.int32(temperature.size),
                np.float64(CUTOFF),
                result,
            ),
        )
        sigma[:] = cp.asnumpy(result)
        del result
    if gas == "CO2":
        sigma += co2_continuum_sigma(nu, temperature, pressure, continuum)

    negative = sigma < 0
    typical_column = 1e21 if gas == "CO2" else 1e19
    diagnostics = {
        "frac_neg": float(negative.mean()),
        "sig_min": float(sigma.min()),
        "tau_neg_max": float(-sigma.min() * typical_column),
        "tau_neg_col": float(-sigma[negative].sum() * typical_column / temperature.size),
    }
    logs = np.log10(np.clip(sigma, 1e-45, None))
    on_gpu = cp.asarray(logs)
    mean = on_gpu.mean(axis=0, keepdims=True)
    left, singular, right = cp.linalg.svd(on_gpu - mean, full_matrices=False)
    u = left[:, :RANK] * singular[:RANK]
    error = cp.sqrt(((on_gpu - (mean + u @ right[:RANK])) ** 2).mean())
    factors = {
        "gas": gas,
        "a": float(start),
        "b": float(end),
        "U": cp.asnumpy(u).astype(np.float32),
        "V": cp.asnumpy(right[:RANK]).astype(np.float32),
        "mu": cp.asnumpy(mean[0]).astype(np.float32),
        "r": RANK,
        "rms_log": float(error),
        "t_kernel": perf_counter() - started,
        "NT": NT,
        "NP": NP,
        "T_LO": T_LOW,
        "T_HI": T_HIGH,
        "P_LO": P_LOW,
        "P_HI": P_HIGH,
        "dnu": STEP,
        **diagnostics,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(output, **factors)
    return {
        "output": str(output),
        "sha256": sha256_file(output),
        "rms_log": factors["rms_log"],
        "negative_fraction": diagnostics["frac_neg"],
        "status": "candidate_historical_source_unverified",
    }


def compare_block(
    candidate: Path, archived: Path, *, states: int = 20, channels: int = 301
) -> dict:
    """Compare reconstructed cross sections on a deterministic canary grid."""
    with (
        np.load(candidate, allow_pickle=False) as left,
        np.load(archived, allow_pickle=False) as right,
    ):
        for key in ("gas", "a", "b", "NT", "NP", "dnu"):
            if np.asarray(left[key]).item() != np.asarray(right[key]).item():
                raise ValueError(f"Candidate and archive disagree on {key}")
        nstate = left["U"].shape[0]
        nchannel = left["mu"].size
        state_index = np.linspace(0, nstate - 1, min(states, nstate), dtype=int)
        channel_index = np.linspace(0, nchannel - 1, min(channels, nchannel), dtype=int)

        def reconstruct(archive):
            u = archive["U"][state_index].astype(np.float64)
            v = archive["V"][:, channel_index].astype(np.float64)
            return archive["mu"][channel_index].astype(np.float64)[None, :] + u @ v

        difference = reconstruct(left) - reconstruct(right)
    return {
        "max_abs_log10_sigma": float(np.max(np.abs(difference))),
        "rms_log10_sigma": float(np.sqrt(np.mean(difference**2))),
        "candidate_sha256": sha256_file(candidate),
        "archived_sha256": sha256_file(archived),
        "status": "comparison_only_no_scientific_acceptance_threshold",
    }
